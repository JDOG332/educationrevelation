sys.path.insert(0, HERE)
import run_v12e as e  # noqa: E402

OUT = e.OUT
_f = e._f


def fam_line(v):
    return ", ".join(f"{k}: {_f(v['family_f'][k])} (n={v['family_n_counted'][k]})" for k in v["family_f"])


def figure(cells):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    cols = {"F_P": "#888888", "F_BC": "#2a78d6", "F_C": "#1baf7a", "F_R": "#eda100", "F_RC": "#eb6834"}
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.8))
    for ax, (xa, title) in zip(axes, (("RA_q", "RA_q (fragments, reset S)"),
                                      ("Helstrom", "RA_rec, Helstrom records"),
                                      ("Local", "RA_rec, Local records"))):
        for fam in e.FAMILIES:
            xs, ys = [], []
            for c in cells:
                if c["family"] != fam:
                    continue
                for r in c["points"]:
                    xs.append(r["RA_q"] if xa == "RA_q" else r["obs"][xa]["RA_rec"])
                    ys.append(r["TYZ_Pi"])
            ax.plot(xs, ys, ".", ms=2, color=cols[fam], label=fam, alpha=0.6)
        ax.plot([-0.2, 1], [-0.2, 1], color="k", lw=0.8, ls=":")
        ax.set_xlabel(title + " (bits)")
        ax.set_title(title)
    axes[0].set_ylabel("TYZ Im(F_A:F_B|S_Pi), S measured (bits)")
    axes[0].legend(markerscale=5, frameon=False, fontsize=8)
    fig.suptitle("Phase 5 main grid (N_E = 16): interventional vs S-measured consensus; dotted line = equality", fontsize=9)
    fig.tight_layout()
    p = os.path.join(OUT, "fig1_phase5_scatter.png")
    fig.savefig(p, dpi=140)
    plt.close(fig)
    return p


